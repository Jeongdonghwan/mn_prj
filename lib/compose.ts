const shuffle = <T,>(arr: T[], s: string, salt: string) => arr.map((x, i) => [seedOf(`${s}::${salt}::${i}`), x] as [number, T]).sort((a, b) => a[0] - b[0]).map((x) => x[1]);
const nsp = (t: string) => t.replace(/\s/g, '').length;
function para(first: string[], rest: string[], s: string, salt: string, keep = false): string {
  const out = [pick(first, s, `${salt}f`)];
  let n = nsp(out[0]);
  for (const x of keep ? rest : shuffle(rest, s, salt)) {
    if (n >= 225) break;
    if (n + nsp(x) > 275) continue;
    out.push(x); n += nsp(x);
  }
  return out.join(' ');
}
const KW_AT = new Set([0, 1, 2, 5]); // 절 6개 중 4개 h2 에 키워드 전체

// title·h1 공용 수식어(2026-11-24): "키워드 수식어" 가 40자를 넘으면 더 짧은 벌을 고르고, 그래도 넘으면 수식어를 낱말 단위로 줄인다.
function fitSub(kw: string, arr: string[], s: string): string {
  const ok = (x: string) => kw.length + 1 + x.length <= 40;
  const first = pick(arr, s, 'h1sub');
  if (ok(first)) return first;
  const fits = arr.filter(ok);
  if (fits.length) return pick(fits, s, 'h1sub2');
  const w = [...arr].sort((a, b) => a.length - b.length)[0].split(' ');
  while (w.length > 1 && !ok(w.join(' '))) w.pop();
  return w.join(' ');
}

